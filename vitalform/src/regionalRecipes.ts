const exclusionsByIngredient: Record<Exclusion, RegExp> = {
  'Dairy / lactose': /\b(curd|yogurt|paneer|ghee|buttermilk|chaas|whey|dairy)\b|(?<!coconut |soy )\bmilk\b/i,
  Gluten: /\b(wheat|dalia|semolina|sooji|oats|maida|bread|toast|pita|atta|thepla|chaap|roti|phulka)\b/i,
  Nuts: /\b(peanuts?|groundnut|walnuts?|almonds?|cashews?|pistachios?)\b/i,
  Soy: /\b(soy|soya|tofu|edamame)\b/i,
  Seafood: /\b(fish|prawns?|shrimp|salmon|tuna|anchov\w*|seafood)\b/i,
};

export function regionalRecipeMatches(recipe: RegionalRecipe, diet: Preference, excluded: readonly Exclusion[], environment: Environment, budget: Budget) {
  const ingredients = recipe.ingredients.map(item => item.name).join(' ');
  const recipeText = `${ingredients} ${recipe.steps.join(' ')}`;
  if ((environment !== 'home' && !recipe.dormFriendly) || tiers.indexOf(recipe.budgetTier) > tiers.indexOf(budget)) return false;
  if (excluded.some(exclusion => exclusionsByIngredient[exclusion].test(ingredients)) ||
      (excluded.includes('Gluten') && (recipe.id === 'south-idli-sambar' || /\b(?:hing|asafoetida)\b/i.test(ingredients)))) return false;
  if (/\b(?:chicken|fish)\b/i.test(ingredients)) return diet === 'Omnivore';
  if (/\begg(?:s)?\b/i.test(ingredients)) return diet === 'Omnivore' || diet === 'Eggetarian';
  if (diet === 'Vegan') return recipe.preference.includes('Vegan') && !exclusionsByIngredient['Dairy / lactose'].test(ingredients);
  if (diet === 'Jain / Satvik') return recipe.preference.includes(diet) && !/\b(?:onions?|garlic|shallots?|carrots?|radish|turnip|ginger|sprouted|fermented|idli)\b/i.test(recipeText);
  return true;
}

