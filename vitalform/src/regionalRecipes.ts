export function regionalRecipeMeetsSafety(recipe: RegionalRecipe, profile: UserBioProfile | null) {
  const flags = profile?.health ?? [];
  return (!flags.includes('diabetes') || reviewedCarbRecipes.has(recipe.id))
    && (!flags.includes('hypertension') || plainSodiumRecipes.has(recipe.id));
}

